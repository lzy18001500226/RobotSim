    parser.add_argument("--close-duration-s", type=float, default=2.0)
    parser.add_argument("--arm-gain-scale", type=float, default=1.0)
    parser.add_argument(
        "--adaptive-bilateral-capture",
        action="store_true",
        help="freeze the single root target at the first sustained, bilateral pad contact",
    )
    parser.add_argument("--capture-force-n", type=float, default=3.0)
    parser.add_argument("--capture-streak-steps", type=int, default=50)
    parser.add_argument("--capture-preload-fraction", type=float, default=0.0)
    parser.add_argument("--capture-hold-duration-s", type=float, default=0.25)
    parser.add_argument(
        "--capture-target-advance-rad",
        type=float,
        default=0.0,
        help="bounded closing-side root-position advance applied once after tactile capture",
    )
    parser.add_argument("--capture-force-servo-n", type=float)
    parser.add_argument("--capture-force-servo-gain-nm-per-n", type=float, default=0.20)
    parser.add_argument("--capture-max-advance-rad", type=float, default=0.015)
    args = parser.parse_args()
    if not args.execute_dynamics:
        raise SystemExit("refusing to run physics without --execute-dynamics")
    if not all(math.isfinite(value) and value > 0.0 for value in (args.root_effort, args.root_kp, args.root_kd, args.arm_gain_scale)):
        raise SystemExit("controller parameters must be positive and finite")
    if args.root_effort > 1.0:
        raise SystemExit("--root-effort must remain in the official normalized 0..1 range")
    if not math.isfinite(args.hold_preload_fraction) or not 0.0 <= args.hold_preload_fraction <= 1.0:
        raise SystemExit("--hold-preload-fraction must remain within 0..1")
    if not math.isfinite(args.hold_preload_band_rad) or args.hold_preload_band_rad <= 0.0:
        raise SystemExit("--hold-preload-band-rad must be positive and finite")
    if not math.isfinite(args.close_duration_s) or args.close_duration_s <= 0.0:
        raise SystemExit("--close-duration-s must be positive and finite")
    if not math.isfinite(args.capture_force_n) or args.capture_force_n <= 0.0:
        raise SystemExit("--capture-force-n must be positive and finite")
    if args.capture_streak_steps <= 0:
        raise SystemExit("--capture-streak-steps must be positive")
    if not math.isfinite(args.capture_preload_fraction) or not 0.0 <= args.capture_preload_fraction <= 1.0:
        raise SystemExit("--capture-preload-fraction must remain within 0..1")
    if not math.isfinite(args.capture_hold_duration_s) or args.capture_hold_duration_s <= 0.0:
        raise SystemExit("--capture-hold-duration-s must be positive and finite")
    if not math.isfinite(args.capture_target_advance_rad) or abs(args.capture_target_advance_rad) > 0.05:
        raise SystemExit("--capture-target-advance-rad must be finite and within +/-0.05 rad")
    if args.capture_force_servo_n is not None and (not math.isfinite(args.capture_force_servo_n) or args.capture_force_servo_n <= 0.0):
        raise SystemExit("--capture-force-servo-n must be positive and finite")
    if not math.isfinite(args.capture_force_servo_gain_nm_per_n) or args.capture_force_servo_gain_nm_per_n <= 0.0:
        raise SystemExit("--capture-force-servo-gain-nm-per-n must be positive and finite")
    if not math.isfinite(args.capture_max_advance_rad) or not 0.0 < args.capture_max_advance_rad <= 0.05:
        raise SystemExit("--capture-max-advance-rad must be in (0, 0.05]")
    if args.capture_force_servo_n is not None and not args.adaptive_bilateral_capture:
        raise SystemExit("--capture-force-servo-n requires --adaptive-bilateral-capture")
    if not args.force_static_result.is_file() or not args.prior_config.is_file() or not args.full_urdf.is_file():
        raise SystemExit("force static result, prior config, or official URDF is missing")
    if sha256(args.full_urdf) != EXPECTED_OFFICIAL_URDF_SHA256:
        raise SystemExit("official URDF hash differs from the pinned v1.4.0 source")
    static = json.loads(args.force_static_result.read_text(encoding="utf-8"))
    required = (
        "FORCE_CONTROL_SCENE_COMPILED",
        "SINGLE_RIGHT_ROOT_MOTOR",
        "FIVE_REVIEWED_FOLLOWER_RELATIONS",
        "FIT_ANGLE_DRIFT_LE_0_5_DEG",
        "P37_BILATERAL_PAD_ONLY_CONTACT",
    )
    if any(static.get("gates", {}).get(gate) != "PASS" for gate in required):
        raise SystemExit("force-control static preflight has not passed")
    scene = Path(static["generated_scene"]["path"])
    if not scene.is_file() or sha256(scene) != static["generated_scene"]["sha256"]:
        raise SystemExit("force-control static scene hash mismatch")
    config = json.loads(args.prior_config.read_text(encoding="utf-8"))
    location = (
        pg.validate_output_path(args.output_dir, require_exists=True, expected_kind="directory")
        if args.output_dir is not None
        else pg.create_unique_output_directory(EVIDENCE_REPO / "reviews/issue-46", prefix="full-x2-stl-force-control-lift")
    )
    output = location.native_path
    if any(path.name != ".robotsim-output-reservation.json" for path in output.iterdir()):
        raise SystemExit("output directory is not fresh")
    model = mujoco.MjModel.from_xml_path(str(scene))
    reference_model = mujoco.MjModel.from_xml_path(str(scene))
    reference_model.opt.disableflags |= int(mujoco.mjtDisableBit.mjDSBL_CONTACT)
    if mujoco.__version__ != "3.3.6" or abs(float(model.opt.timestep) - DT) > 1e-12:
        raise SystemExit("unexpected MuJoCo runtime or timestep")
    root_motor = actuator_id(model, "motor_right_claw_stl_force")
    root_low, root_high = (float(value) for value in model.actuator_ctrlrange[root_motor])
    if abs(root_low + float(static["overlay"]["root_torque_cap_nm"])) > 1e-12 or abs(root_high - float(static["overlay"]["root_torque_cap_nm"])) > 1e-12:
        raise SystemExit("right root motor range differs from static preflight")
    data = mujoco.MjData(model)
